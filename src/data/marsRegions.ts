function createQuadPoly(
  minLat: number,
  maxLat: number,
  minLng: number,
  maxLng: number,
  steps = 6
): [number, number][] {
  const coords: [number, number][] = [];
  for (let i = 0; i <= steps; i++) {
    coords.push([minLat, minLng + ((maxLng - minLng) * i) / steps]);
  }
  for (let i = 1; i <= steps; i++) {
    coords.push([minLat + ((maxLat - minLat) * i) / steps, maxLng]);
  }
  for (let i = 1; i <= steps; i++) {
    coords.push([maxLat, maxLng - ((maxLng - minLng) * i) / steps]);
  }
  for (let i = 1; i < steps; i++) {
    coords.push([maxLat - ((maxLat - minLat) * i) / steps, minLng]);
  }
  return coords;
}


// Ray-casting point-in-polygon algorithm to check if a lat/lng is inside a polygon
export function isPointInMarsRegion(lat: number, lng: number, polygon: [number, number][]): boolean {
  // Normalize lng to -180..180
  let normLng = ((((lng + 180) % 360) + 360) % 360) - 180;
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const xi = polygon[i][1], yi = polygon[i][0];
    const xj = polygon[j][1], yj = polygon[j][0];
    const intersect = yi > lat !== yj > lat && normLng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

// Helper to generate circular polygon vertices for circular basins/craters
function createCirclePolygon(centerLat: number, centerLng: number, radiusLatDeg: number, radiusLngDeg: number, points = 24): [number, number][] {
  const coords: [number, number][] = [];
  for (let i = 0; i < points; i++) {
    const angle = (i / points) * 2 * Math.PI;
    const lat = Number((centerLat + radiusLatDeg * Math.sin(angle)).toFixed(3));
    const lng = Number((centerLng + radiusLngDeg * Math.cos(angle)).toFixed(3));
    coords.push([lat, lng]);
  }
  return coords;
}

